let current = 'zh'
/** @type {'auto' | string} */
let preference = 'auto'

export function getLocale() {
  return current
}

export function getLocalePreference() {
  return preference
}

export function setLocale(id) {
  if (id === 'auto') {
    preference = 'auto'
    current = detectSystemLocale()
    return current
  }
  preference = id
  current = STRINGS[id] ? id : 'zh'
  return current
}

export function detectSystemLocale() {
  const list = [...(navigator.languages || []), navigator.language || 'zh']
  for (const raw of list) {
    const nav = String(raw || '').slice(0, 2).toLowerCase()
    if (nav && STRINGS[nav]) return nav
  }
  return 'zh'
}

/**
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.zh
  let s = table[key] ?? STRINGS.zh[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}

export function detectLocale() {
  const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('codepaste-locale') : null
  let installLocale = null
  try {
    installLocale = new URLSearchParams(location.search).get('installLocale')
  } catch {
    installLocale = null
  }
  return resolveStartLocale({ saved, installLocale })
}
